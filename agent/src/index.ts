import { config } from './config.js';
import { logger } from './logger.js';
import { getUnprocessedIssues, addComment, addLabels, closeIssue, createDraftPR } from './github.js';
import type { GitHubIssue } from './github.js';
import { parseIssueBody } from './issueParser.js';
import { investigate, fix } from './claudeAgent.js';
import { reportResults } from './reportResults.js';
import type { TriageResult } from './types.js';

async function triageIssue(issue: GitHubIssue): Promise<TriageResult> {
  const report = parseIssueBody(issue);
  logger.info(`Processing issue #${report.issueNumber}: ${report.title}`);

  // Phase 1: Investigate
  const investigation = await investigate(report);
  logger.info(`Issue #${report.issueNumber}: isValidBug=${investigation.isValidBug}, confidence=${investigation.confidence}, canAutoFix=${investigation.canAutoFix}`);

  let totalCost = investigation.costUsd;

  const result: TriageResult = {
    issueNumber: report.issueNumber,
    issueUrl: report.issueUrl,
    title: report.title,
    decision: 'not-a-bug',
    confidence: investigation.confidence,
    explanation: investigation.explanation,
    reporterEmail: report.reporterEmail,
    reporterName: report.reporterName,
    branchName: null,
    prUrl: null,
    prNumber: null,
    changedFiles: [],
    costUsd: 0,
  };

  if (!investigation.isValidBug) {
    // Not a bug
    result.decision = 'not-a-bug';
    await addComment(report.issueNumber, [
      `## Triage Agent — Not a Bug`,
      ``,
      investigation.explanation,
      ``,
      `*Confidence: ${investigation.confidence} | Category: ${investigation.category}*`,
    ].join('\n'));
    await addLabels(report.issueNumber, ['not-a-bug']);
    await closeIssue(report.issueNumber);
  } else if (!investigation.canAutoFix || investigation.confidence === 'low') {
    // Valid bug, needs human review
    result.decision = 'needs-review';
    await addComment(report.issueNumber, [
      `## Triage Agent — Needs Human Review`,
      ``,
      investigation.explanation,
      ``,
      `**Category:** ${investigation.category}`,
      `**Affected files:** ${investigation.affectedFiles.join(', ') || 'unknown'}`,
      investigation.suggestedFix ? `**Suggested fix:** ${investigation.suggestedFix}` : '',
      ``,
      `*Confidence: ${investigation.confidence} — routed for manual review*`,
    ].filter(Boolean).join('\n'));
    await addLabels(report.issueNumber, ['needs-human-review']);
  } else {
    // Valid bug, auto-fixable
    result.decision = 'auto-fixed';
    const fixResult = await fix(report, investigation);

    if (fixResult) {
      totalCost += fixResult.costUsd;
      const pr = await createDraftPR(fixResult.branchName, fixResult.prTitle, [
        fixResult.prBody,
        ``,
        `Fixes #${report.issueNumber}`,
        ``,
        `---`,
        `*This PR was generated by the triage agent. Please review before merging.*`,
      ].join('\n'));

      result.branchName = fixResult.branchName;
      result.prUrl = pr.html_url;
      result.prNumber = pr.number;
      result.changedFiles = fixResult.changedFiles;

      await addComment(report.issueNumber, [
        `## Triage Agent — Fix Proposed`,
        ``,
        `A fix has been created: ${pr.html_url}`,
        ``,
        `**Changed files:** ${fixResult.changedFiles.join(', ')}`,
        ``,
        `*The fix is pending review and will be merged if approved.*`,
      ].join('\n'));
      await addLabels(report.issueNumber, ['fix-proposed']);
    } else {
      // Fix generation failed, fall back to human review
      result.decision = 'needs-review';
      await addComment(report.issueNumber, [
        `## Triage Agent — Fix Attempt Failed`,
        ``,
        `The bug was confirmed but the automatic fix failed. Routing for manual review.`,
        ``,
        `**Investigation:** ${investigation.explanation}`,
        `**Affected files:** ${investigation.affectedFiles.join(', ') || 'unknown'}`,
      ].join('\n'));
      await addLabels(report.issueNumber, ['needs-human-review']);
    }
  }

  // Always mark as processed
  await addLabels(report.issueNumber, ['triage-processed']);

  result.costUsd = totalCost;
  return result;
}

async function main(): Promise<void> {
  const startedAt = new Date().toISOString();
  logger.info(`=== Triage Agent started${config.DRY_RUN ? ' (DRY RUN)' : ''} ===`);
  logger.info(`Project root: ${config.PROJECT_ROOT}`);

  const issues = await getUnprocessedIssues();
  logger.info(`Found ${issues.length} unprocessed issue${issues.length === 1 ? '' : 's'}`);

  if (issues.length === 0) {
    logger.info('Nothing to process. Exiting.');
    return;
  }

  const results: TriageResult[] = [];

  for (const issue of issues) {
    try {
      const result = await triageIssue(issue);
      results.push(result);
      logger.info(`Issue #${issue.number}: ${result.decision}`);
    } catch (err) {
      logger.error(`Failed to process issue #${issue.number}: ${err}`);
      results.push({
        issueNumber: issue.number,
        issueUrl: issue.html_url,
        title: issue.title,
        decision: 'error',
        confidence: 'low',
        explanation: `Processing failed: ${err}`,
        reporterEmail: null,
        reporterName: null,
        branchName: null,
        prUrl: null,
        prNumber: null,
        changedFiles: [],
        costUsd: 0,
      });
      try {
        await addLabels(issue.number, ['triage-error']);
      } catch {
        // ignore label failure
      }
    }
  }

  const finishedAt = new Date().toISOString();

  // POST results to server (server handles emails + stores in DB for admin page)
  await reportResults(startedAt, finishedAt, results);

  logger.info(`=== Triage complete: ${results.length} issue${results.length === 1 ? '' : 's'} processed ===`);
}

main().catch(err => {
  logger.error(`Fatal error: ${err}`);
  process.exit(1);
});
